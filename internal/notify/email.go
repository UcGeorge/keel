// Subject is the email subject line for an event.
func (e Event) Subject() string {
	return "[Keel] " + e.Title
}

// tone picks the badge text and accent color for an event, matching the
// status colors of the web UI.
func (e Event) tone() (label, color, soft string) {
	switch e.Kind {
	case RunSucceeded:
		return "Succeeded", "#047857", "#ecfdf5"
	case RunFailed:
		return "Failed", "#b91c1c", "#fef2f2"
	case RunCanceled:
		return "Canceled", "#475569", "#f1f5f9"
	case RunStarted:
		return "Started", "#0369a1", "#f0f9ff"
	case "test":
		return "Test", "#0f766e", "#f0fdfa"
	default:
		return Label(string(e.Kind)), "#0f766e", "#f0fdfa"
	}
}

// Text renders the plain-text alternative.
func (e Event) Text() string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\n%s\n\n", e.Title, strings.Repeat("=", len([]rune(e.Title))))
	if e.Summary != "" {
		b.WriteString(e.Summary + "\n\n")
	}
	if e.Error != "" {
		fmt.Fprintf(&b, "Error: %s\n\n", e.Error)
	}
	for _, f := range e.Facts {
		fmt.Fprintf(&b, "%-14s %s\n", f.Label+":", f.Value)
	}
	if len(e.Inputs) > 0 {
		b.WriteString("\nDeploy-time inputs:\n")
		for _, f := range e.Inputs {
			fmt.Fprintf(&b, "  %s = %s\n", f.Label, f.Value)
		}
	}
	if e.Insight != "" {
		b.WriteString("\nAI insight\n----------\n")
		b.WriteString(strings.TrimSpace(e.Insight) + "\n")
		b.WriteString("\n(Generated by a language model from the run's log, steps, and non-secret inputs. Check it against the log before acting on anything irreversible.)\n")
	} else if e.InsightNote != "" {
		b.WriteString("\nAI insight: " + e.InsightNote + "\n")
	}
	if len(e.LogTail) > 0 {
		fmt.Fprintf(&b, "\nLast %d log lines:\n", len(e.LogTail))
		b.WriteString(strings.Repeat("-", 40) + "\n")
		for _, l := range e.LogTail {
			b.WriteString(l + "\n")
		}
		b.WriteString(strings.Repeat("-", 40) + "\n")
	}
	if e.Link != "" {
		label := e.LinkLabel
		if label == "" {
			label = "Open in Keel"
		}
		fmt.Fprintf(&b, "\n%s: %s\n", label, e.Link)
	}
	fmt.Fprintf(&b, "\n--\n%s", e.reason())
	if e.SettingsLink != "" {
		fmt.Fprintf(&b, " Manage recipients and events: %s", e.SettingsLink)
	}
	b.WriteString("\n")
	return b.String()
}

// reason tells the reader why the email arrived.
func (e Event) reason() string {
	if info, ok := Lookup(string(e.Kind)); ok {
		return fmt.Sprintf("You receive this because you are subscribed to \u201c%s\u201d events for %s in Keel Cloud.", info.Label, e.OrgName)
	}
	return fmt.Sprintf("Sent from the notification settings of %s in Keel Cloud.", e.OrgName)
}

// md renders the insight's Markdown. Raw HTML is dropped by goldmark's
// default policy, so model output can be inlined safely.
var md = goldmark.New(goldmark.WithExtensions(extension.GFM))

func renderMarkdown(src string) template.HTML {
	var buf bytes.Buffer
	if err := md.Convert([]byte(src), &buf); err != nil {
		return template.HTML(template.HTMLEscapeString(src))
	}
	// Inline styles for email clients, which ignore <style> blocks in many
	// cases: headings become small caps labels, lists and code get spacing.
	out := buf.String()
	out = strings.ReplaceAll(out, "<h2>", `<h2 style="margin:16px 0 4px;font-size:11px;font-weight:700;letter-spacing:.08em;text-transform:uppercase;color:#5b21b6;">`)
	out = strings.ReplaceAll(out, "<h3>", `<h3 style="margin:14px 0 4px;font-size:13px;font-weight:700;color:#0f172a;">`)
	out = strings.ReplaceAll(out, "<p>", `<p style="margin:4px 0 8px;font-size:14px;line-height:1.55;color:#0f172a;">`)
	out = strings.ReplaceAll(out, "<ul>", `<ul style="margin:4px 0 8px 20px;padding:0;font-size:14px;line-height:1.55;color:#0f172a;">`)
	out = strings.ReplaceAll(out, "<ol>", `<ol style="margin:4px 0 8px 20px;padding:0;font-size:14px;line-height:1.55;color:#0f172a;">`)
	out = strings.ReplaceAll(out, "<li>", `<li style="margin:2px 0;">`)
	out = strings.ReplaceAll(out, "<code>", `<code style="font-family:'JetBrains Mono',ui-monospace,SFMono-Regular,Menlo,Consolas,monospace;font-size:12px;background:#f1f5f9;border-radius:4px;padding:1px 5px;">`)
	out = strings.ReplaceAll(out, "<pre>", `<pre style="margin:6px 0 10px;padding:10px 12px;background:#020617;color:#e2e8f0;border-radius:8px;font-size:12px;line-height:1.5;white-space:pre-wrap;word-break:break-all;">`)
	out = strings.ReplaceAll(out, "<blockquote>", `<blockquote style="margin:6px 0;padding-left:12px;border-left:3px solid #e2e8f0;color:#475569;">`)
	return template.HTML(out)
}

