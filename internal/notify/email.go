// HTML renders the HTML body.
func (e Event) HTML() string {
	badge, color, soft := e.tone()
	label := e.LinkLabel
	if label == "" {
		label = "Open in Keel"
	}
	preheader := e.Summary
	if preheader == "" {
		preheader = e.Title
	}
	data := map[string]any{
		"Title": e.Title, "Summary": e.Summary, "OrgName": e.OrgName, "Preheader": preheader,
		"Badge": badge, "Color": color, "Soft": soft, "Error": e.Error,
		"Facts": e.Facts, "Inputs": e.Inputs, "LogTail": e.LogTail,
		"Link": e.Link, "LinkLabel": label, "SettingsLink": e.SettingsLink, "Reason": e.reason(),
		"Insight": template.HTML(""), "InsightNote": e.InsightNote,
	}
	if e.Insight != "" {
		data["Insight"] = renderMarkdown(e.Insight)
	}
	var buf bytes.Buffer
	if err := emailTmpl.Execute(&buf, data); err != nil {
		return "<pre>" + template.HTMLEscapeString(e.Text()) + "</pre>"
	}
	return buf.String()
}
